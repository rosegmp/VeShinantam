    private val range = Regex("""(\d+):(\d+)-(?:(\d+):)?(\d+|End)""")

    private fun hebrewPortion(portion: String): String {
        if (portion == "Klalim") return "כללים"
        val match = requireNotNull(range.matchEntire(portion)) { "Invalid Kitzur reading: $portion" }
        val (startChapter, startSeif, endChapter, endSeif) = match.destructured
        val end = endChapter.takeIf(String::isNotEmpty)?.let {
            "${PresetHebrewNumerals.format(it.toInt())}:"
        }.orEmpty() + if (endSeif == "End") "סוף" else PresetHebrewNumerals.format(endSeif.toInt())
        return "${PresetHebrewNumerals.format(startChapter.toInt())}:${PresetHebrewNumerals.format(startSeif.toInt())}-$end"
    }

