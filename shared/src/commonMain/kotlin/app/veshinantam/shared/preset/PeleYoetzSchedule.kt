    private fun parseVolume(volume: Int, precedingDays: Int, data: String): List<UnitReference> =
        data.trimIndent().lines().mapIndexed { index, row ->
            val day = precedingDays + index + 1
            val otHebrew = row.substringBefore('|')
            val beginning = row.substringAfter('|')
            val otEnglish = when (otHebrew) {
                "א" -> "Alef"
                "ב" -> "Bet"
                "ג" -> "Gimel"
                "ד" -> "Dalet"
                "ה" -> "Heh"
                "ו" -> "Vav"
                "ז" -> "Zayin"
                "ח" -> "Chet"
                "ט" -> "Tet"
                "י" -> "Yod"
                else -> "Kaf"
            }
            UnitReference(
                english = "Pele Yoetz, Volume $volume, Day $day, Ot $otEnglish - $beginning",
                hebrew = "פלא יועץ, חלק ${PresetHebrewNumerals.format(volume)}, יום ${PresetHebrewNumerals.format(day)}, אות $otHebrew - $beginning",
            )
        }
